    public static function isEnabled(): bool
    {
        return (bool) config('demo.midterm_demo_enabled', true);
    }

    public static function isRequestBlocked(Request $request): bool
    {
        if (!self::isEnabled()) {
            return false;
        }

        $action = $request->route()?->getActionName();
        if ($action && in_array($action, self::DISABLED_ACTIONS, true)) {
            return true;
        }

        foreach (self::DISABLED_URI_PATTERNS as $pattern) {
            if ($request->is($pattern)) {
                return true;
            }
        }

        return false;
    }
